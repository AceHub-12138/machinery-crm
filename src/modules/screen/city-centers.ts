/**
 * 获取城市级中心点坐标；省份与城市都必须是自有属性键（拒绝原型链键与原型污染），
 * 城市不存在或坐标表未收录时返回 null（由调用方回退省级中心）
 */
export function getCityCenter(province: string, city: string | null): GeoCenter | null {
  if (!province || !city) {
    return null;
  }
  if (!Object.prototype.hasOwnProperty.call(CITY_CENTERS, province)) {
    return null;
  }
  const cities = CITY_CENTERS[province];
  if (!cities || typeof cities !== "object" || !Object.prototype.hasOwnProperty.call(cities, city)) {
    return null;
  }
  const center = (cities as Record<string, unknown>)[city];
  if (!center || typeof center !== "object") {
    return null;
  }
  if (
    !Object.prototype.hasOwnProperty.call(center, "lat") ||
    !Object.prototype.hasOwnProperty.call(center, "lng")
  ) {
    return null;
  }
  const { lat, lng } = center as Record<"lat" | "lng", unknown>;
  if (
    typeof lat !== "number" ||
    typeof lng !== "number" ||
    !Number.isFinite(lat) ||
    !Number.isFinite(lng) ||
    lat < -90 ||
    lat > 90 ||
    lng < -180 ||
    lng > 180
  ) {
    return null;
  }
  return { lat, lng };
}
